# --- build flow ------------------------------------------------------------


class FakeIde:
    """Writes the ELFs a headless build would, containing the Build ID read from the header."""

    def __init__(self, bt, log_text, code=0, write_elfs=True):
        self.bt, self.log_text, self.code, self.write_elfs = bt, log_text, code, write_elfs
        self.cmds = []

    def __call__(self, cmd):
        self.cmds.append(cmd)
        if self.write_elfs:
            header = self.bt.overrides_h.read_text()
            bid = header.split('BENCH_BUILD_ID "')[1].split('"')[0]
            for i, a in enumerate(cmd):
                if a in ("-build", "-cleanBuild"):
                    project, config = cmd[i + 1].split("/")
                    core = project.removeprefix("ArcLoRaM_Base_")
                    elf = self.bt.elf(core, config)
                    elf.parent.mkdir(parents=True, exist_ok=True)
                    elf.write_bytes(b"\x7fELF..." + bid.encode() + b"...")
        return self.code, self.log_text


def ok_log(configs):
    return "".join(f"**** Build of configuration {c} for project ArcLoRaM_Base_{core} ****\n"
                   f"Build Finished. 0 errors, 0 warnings. (took 1s)\n"
                   for c in configs for core in ("CM4", "CM0PLUS"))


def no_sync(repo, tree):
    tree.mkdir(parents=True, exist_ok=True)


def test_build_writes_the_header_and_checks_the_images(repo, tmp_path):
    bt = BuildTree(tmp_path / "bench")
    ide = FakeIde(bt, ok_log(["Debug_C2"]))
    r = build(repo, bt, ["C2", "C2"], {"TX_RAMP_MS": "5u"}, runner=ide, cubeide="ide.exe", sync_tree=no_sync, windows=str)
    assert r.ok, r.problems
    assert r.configs == ["Debug_C2"]
    assert f'#define BENCH_BUILD_ID "{r.build_id}"' in bt.overrides_h.read_text()
    assert "#define TX_RAMP_MS 5u" in bt.overrides_h.read_text()
    assert sorted(r.elfs) == [("CM0PLUS", "Debug_C2"), ("CM4", "Debug_C2")]


