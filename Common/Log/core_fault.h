/*!
 * \file      core_fault.h
 *
 * \brief     The target side of the crash record and the reset cause (#101):
 *            the fault entry of both cores, the report at BOOT, and the CM4
 *            read of the reset flags.
 *
 * \details   The pure parts are core_crash.h (the record) and reset_cause.h
 *            (the decoding); this is the glue that only runs on a core.
 *
 *            The fault handlers of both cores used to be `while (1)`. They now
 *            start with \ref CORE_FAULT_ENTRY, which finds the frame the
 *            hardware stacked and hands it to \ref CoreFault_OnException; that
 *            stores the record in the shared region and stops, exactly as the
 *            handler did before (restarting the core is #106's decision). The
 *            next reset, a human's or bench's, reports the record at BOOT.
 *
 *            The handlers are generated by CubeMX, whose bodies can only be
 *            edited in the USER CODE regions, so the entry is a macro placed
 *            in the region and the function is declared `naked` in the USER
 *            CODE region of stm32wlxx_it.h: with a compiler prologue the stack
 *            pointer would already have moved and the frame could not be found.
 *
 *            What it cannot record: a lockup (a fault while a fault handler is
 *            already running, or while the exception entry itself faults)
 *            takes no handler at all. The CM4 of events 3 and 4 locked up. With
 *            BusFault, UsageFault and MemManage enabled (\ref CoreFault_Init)
 *            the first fault of such a chain is taken by its own handler, which
 *            is entered and records; a lockup that remains leaves no record,
 *            which the missing record then says.
 *
 * \author    Simon R.C. Langlais ( Celium )
 *
 */
#ifndef CORE_FAULT_H
#define CORE_FAULT_H

#include <stdint.h>
#include "core_crash.h"
#include "reset_cause.h"

#define CORE_FAULT_STR_(x)  #x
#define CORE_FAULT_STR(x)   CORE_FAULT_STR_(x)

/*!
 * \brief   First statement of a fault handler declared `naked`: pick the stack
 *          the exception was taken on (EXC_RETURN bit 2), pass its top, the
 *          EXC_RETURN value and \c kind (a CORE_CRASH_KIND_*) to
 *          \ref CoreFault_OnException. Never returns.
 *
 * \details Thumb-1 only (movs, mov, tst, mrs, bl), so the same text assembles
 *          for the Cortex-M0+ and the Cortex-M4.
 */
#define CORE_FAULT_ENTRY(kind)                                  \
    __asm volatile(                                             \
        "movs r0, #4                          \n"               \
        "mov  r1, lr                          \n"               \
        "tst  r0, r1                          \n"               \
        "beq  1f                              \n"               \
        "mrs  r0, psp                         \n"               \
        "b    2f                              \n"               \
        "1:                                   \n"               \
        "mrs  r0, msp                         \n"               \
        "2:                                   \n"               \
        "mov  r1, lr                          \n"               \
        "movs r2, #" CORE_FAULT_STR(kind) "   \n"               \
        "bl   CoreFault_OnException           \n")

/*! Store the crash record of this core, then stop. */
void CoreFault_OnException(const uint32_t *frame, uint32_t exc_return, uint32_t kind)
    __attribute__((noreturn, used));

/*! CM4: enable the BusFault, UsageFault and MemManage handlers, so that a fault is named, not forced into a HardFault. */
void CoreFault_Init(void);

/*! CM4, first thing in main(): keep RCC_CSR for the CM0+ and clear it. */
void CoreFault_CaptureResetCause(void);

/*! The cause decoded from the flags the CM4 kept, for the BOOT line of either core. */
const char *CoreFault_ResetName(void);

/*! The raw flags the CM4 kept, for the BOOT line of either core. */
uint32_t CoreFault_ResetFlags(void);

/*! At BOOT, after the BOOT line: print this core's crash record if it left one, and clear it. */
void CoreFault_ReportAtBoot(void);

/*!
 * Build Overrides for the bench (test only, compiled in by no other build). Each acts on one core and
 * one board, once, \c BENCH_FAULT_AFTER_S seconds (default 60) after the boot of that board:
 *   BENCH_FAULT_CM4 / BENCH_FAULT_CM0 = <kind>   force a fault in the main loop
 *       1  an instruction fetch from an address with no memory (IBUSERR on the CM4, as events 3 and 4)
 *       2  an undefined instruction (UNDEFINSTR on the CM4)
 *       3  a data read from an address with no memory (PRECISERR with BFAR on the CM4)
 *       4  as 1 with the BusFault handler off (the CM4 takes the forced HardFault of events 3 and 4)
 *      The CM0+ takes a HardFault for all four.
 *   BENCH_LOOP_CM4 / BENCH_LOOP_CM0 = <checkpoint id>   loop for ever at the first pass of that checkpoint
 *   BENCH_SKIP_ALARM = 1   (CM0+) do not program one Alarm A: a lost wake, the promise still made
 * BENCH_FAULT_NODE names the one board: an override reaches every board the run flashes, the C3
 * too, so a scenario that does not name one acts on them all. The forced act does not repeat at the
 * boot that follows it, so the node runs normally after that reset and reports what it left; a later
 * reset arms it again. Each core ignores the other's override.
 */
#if defined(CORE_CM0PLUS)
#  if defined(BENCH_FAULT_CM0)
#    define CORE_FAULT_KIND       BENCH_FAULT_CM0
#  endif
#  if defined(BENCH_LOOP_CM0)
#    define CORE_FAULT_LOOP_ID    BENCH_LOOP_CM0
#  endif
#  if defined(BENCH_SKIP_ALARM)
#    define CORE_FAULT_SKIP_ALARM 1
#  endif
#else
#  if defined(BENCH_FAULT_CM4)
#    define CORE_FAULT_KIND       BENCH_FAULT_CM4
#  endif
#  if defined(BENCH_LOOP_CM4)
#    define CORE_FAULT_LOOP_ID    BENCH_LOOP_CM4
#  endif
#endif

#if defined(CORE_FAULT_KIND) || defined(CORE_FAULT_LOOP_ID) || defined(CORE_FAULT_SKIP_ALARM)
#  define CORE_FAULT_BENCH  1
void CoreFault_BenchPoll(void);
#else
#  define CoreFault_BenchPoll()  ((void)0)
#endif

#if defined(CORE_FAULT_LOOP_ID)
/*! Called at every checkpoint: loops for ever at the chosen one, once the time has come. */
void CoreFault_BenchAt(uint8_t id);
#else
#  define CoreFault_BenchAt(id)  ((void)0)
#endif

#if defined(CORE_FAULT_SKIP_ALARM)
/*! True once, when the time has come: the caller then does not program its alarm. */
bool CoreFault_BenchSkipAlarm(void);
#else
#  define CoreFault_BenchSkipAlarm()  (false)
#endif

#endif /* CORE_FAULT_H */
